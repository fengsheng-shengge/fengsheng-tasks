//   - 本文件属**上层**：行业专用（各领域的轴/节点/维度/话术），按领域增补；
//   - engine.js 属**底层通用**：检索打分、说/带/问/跟生成、法源判定，一次做好全领域复用。
//
// 【铁律】配置只允许声明「检索什么、怎么称呼客户、何时跟进」，
//   不得在本文件内编造词条内容；内容一律来自权威基线（entries_5000.json / 后端 API）。
//
// 【扩域操作指引】
//   1) 在 AXIS_GROUPS 增一个 type（如 operate 资产运营线），给 clientType；
//   2) 在该 type 下增 nodes，每个节点写自己的 kw（检索词）与 label；
//   3) 若该领域有专属维度（如资产运营的「投入产出」），在 DOMAIN_DIMENSIONS 增 key，
//      引擎会自动并入检索词与 UI 维度标签，无需改引擎；
//   4) 若该领域节点需要专属跟进话术，在 FOLLOWUP_PLAYBOOKS 增同名 key；
//   5) 若该领域知识域尚未部署后端 API，把 scene 值加进 engine.js 的
//      STATIC_FALLBACK_SCENES（唯一还需引擎感知的地方，属「数据兜底」而非「领域知识」）。
// ============================================================================

