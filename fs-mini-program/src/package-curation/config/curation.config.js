/**
 * 校验配置自洽性——扩域后跑一次，避免节点漏配话术这类静默问题。
 * 返回问题清单（空数组 = 配置健康）。
 */
export function validateCurationConfig(cfg = {}) {
  const groups = cfg.axisGroups || AXIS_GROUPS
  const plays = cfg.followupPlaybooks || FOLLOWUP_PLAYBOOKS
  const issues = []
  const seenKeys = new Set()
  groups.forEach(g => {
    if (!g.type || !g.label || !g.clientType) issues.push(`轴「${g.type || '?'}」缺 type/label/clientType`)
    ;(g.nodes || []).forEach(n => {
      if (seenKeys.has(n.key)) issues.push(`节点 key 重复：${n.key}（跨轴需全局唯一）`)
      seenKeys.add(n.key)
      if (!Array.isArray(n.kw) || n.kw.length === 0) issues.push(`节点「${n.key}」kw 为空，检索不到内容`)
      if (!plays[n.key] && !(Array.isArray(n.followups) && n.followups.length)) {
        issues.push(`节点「${n.key}」缺跟进话术，将落到兜底`)
      }
    })
  })
  return issues
}