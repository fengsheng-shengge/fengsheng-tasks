// 【为什么解耦】原 engine.js 把「双纵轴节点关键词 / 七维关键词 / 见后跟进话术」
//   三处写死在代码里，扩一个新领域（如 Phase 2 资产运营、Phase 3 家装）就必须
//   改引擎源码，违背「底层引擎通用、只灌知识」的架构承诺。本文件把这三类
//   **领域相关**配置抽出来，引擎只负责检索逻辑 —— 新增领域只改本文件，不碰引擎。
//
