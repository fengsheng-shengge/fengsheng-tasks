import json
import os
import sys
from datetime import date

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTRIES_PATH = os.path.join(BASE, 'data', 'entries.json')
TODAY = str(date.today())

# ---------- 加载 ----------
with open(ENTRIES_PATH, 'r', encoding='utf-8') as f:
    entries = json.load(f)

existing_ids = {e['id'] for e in entries}

def make_id(prefix, domain, seq):
    """生成不重复 id"""
    base = f"{prefix}-{domain}-{seq:03d}"
    while base in existing_ids:
        seq += 1
        base = f"{prefix}-{domain}-{seq:03d}"
    existing_ids.add(base)
    return base

def build_entry(id_, name, domain, scene_domain, sub_scene,
                consumer_q, consumer_benefit, detail, ola,
                source, priority='P0', severity='hard', entry_type='KNOWLEDGE',
                tool_type='参考卡', client_types=None, stages=None,
                layers=None, legal_ref='', data_ref='', aliases=None,
                owner_benefit=None):
    if client_types is None: client_types = ['elderly']
    if stages is None: stages = ['all']
    if layers is None: layers = ['qi']
    if aliases is None: aliases = []
    if owner_benefit is None: owner_benefit = consumer_benefit

    return {
        "id": id_,
        "domain": domain,
        "sceneDomain": scene_domain,
        "subScene": sub_scene,
        "name": name,
        "alias": aliases,
        "legalRef": legal_ref,
        "consumerQ": consumer_q,
        "consumerBenefit": consumer_benefit,
        "ownerBenefit": owner_benefit,
        "severity": severity,
        "lastVerified": TODAY,
        "relatedEntries": [],
        "source": source,
        "entryType": entry_type,
        "toolType": tool_type,
        "priority": priority,
        "dataSource": source + (f"（{legal_ref}）" if legal_ref else ""),
        "tags": {
            "clientType": client_types,
            "stage": stages,
            "layer": layers,
            "meetingPhase": []
        },
        "detail": detail,
        "ola": ola,
        "cp": [],
        "dataRef": data_ref or legal_ref,
        "caseRef": []
    }

